const { chromium } = require('playwright');
const { openDatabase } = require('../server/db');
const { createApplication } = require('../server/app');
const { hashPassword, digest } = require('../server/security');
const rpg = require('../server/rpg');
const http = require('node:http');
const assert = require('node:assert/strict');

(async () => {
  const db = openDatabase(':memory:');
  const password = 'correct horse battery staple';
  const passwordHash = await hashPassword(password);
  db.prepare("INSERT INTO users VALUES('alice','Alice',?,'user','active','en',1)").run(passwordHash);
  db.prepare("INSERT INTO users VALUES('bob','Bob',?,'user','active','en',1)").run(passwordHash);
  const data = rpg.createEntity('character', { key: 'test-character' });
  data.name.firstName = 'Test';
  data.name.lastName = 'Hero';
  db.prepare("INSERT INTO entities(id,type,owner_id,data,version,created_at) VALUES(?,'character','alice',?,0,1)").run(data.key, JSON.stringify(data));
  db.prepare("INSERT INTO entity_history(entity_id,version,data,created_at,actor_id) VALUES(?,0,?,1,'alice')").run(data.key, JSON.stringify(data));
  db.prepare("INSERT INTO campaigns(id,name,language,owner_id,created_at) VALUES('camp','Test campaign','en','alice',1)").run();
  db.prepare("INSERT INTO members VALUES('camp','alice','gm')").run();
  db.prepare("INSERT INTO members VALUES('camp','bob','member')").run();
  db.prepare("INSERT INTO assignments VALUES('test-character','camp','approved','shared',1)").run();
  const app = createApplication(db);
  const server = http.createServer(app.handler);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  let browser;
  try {
    browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
    const context = await browser.newContext();
    await context.addInitScript(() => {
      const NativeEventSource = window.EventSource;
      window.eventOpenCount = 0;
      window.EventSource = class extends NativeEventSource {
        constructor(...args) { super(...args); this.addEventListener('open', () => window.eventOpenCount++); }
      };
    });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    await page.locator('#auth-form [name=username]').fill('Alice');
    await page.locator('#auth-form [name=password]').fill(password);
    await page.locator('#auth-form button').click();
    await page.locator('a[href="#/characters"]').first().waitFor();
    await page.locator('a[href="#/characters"]').first().click();
    await page.locator('text=Test Hero').first().waitFor();
    await page.locator('a[href="#/sheet/test-character"]').first().click();
    await page.locator('[data-action=lock-start]').click();
    await page.locator('[data-action=lock-finish]').waitFor();
    const other = await context.newPage();
    other.on('pageerror', error => errors.push(error.message));
    await other.goto(`${url}/#/sheet/test-character`);
    await other.locator('.sheet-heading').waitFor();
    await other.locator('text=Currently edited by').waitFor();
    await other.locator('[data-action=lock-start]').click();
    await other.locator('#notice.error').waitFor();
    await page.locator('[data-field="name.firstName"]').fill('Updated');
    await page.locator('[data-action=lock-finish]').click();
    await page.locator('[data-action=lock-start]').waitFor();
    assert.equal(JSON.parse(db.prepare("SELECT data FROM entities WHERE id='test-character'").get().data).name.firstName, 'Updated');
    await other.locator('text=Currently edited by').waitFor({ state: 'hidden' });
    await other.locator('[data-action=lock-start]').click();
    await other.locator('[data-action=lock-finish]').waitFor();
    await other.locator('[data-action=lock-finish]').click();
    await other.locator('[data-action=lock-start]').waitFor();
    await page.locator('text=Currently edited by').waitFor({ state: 'hidden' });
    await page.locator('[data-action=lock-start]').click();
    await page.locator('[data-action=lock-finish]').waitFor();
    await page.locator('[data-field="name.lastName"]').fill('Wayfarer');
    await page.locator('#masthead a[href="#/dice"]').click();
    await page.locator('#dice-form').waitFor();
    assert.equal(JSON.parse(db.prepare("SELECT data FROM entities WHERE id='test-character'").get().data).name.lastName, 'Wayfarer');

    await page.goto(`${url}/#/campaign/camp/overview`);
    await page.locator('.battle-panel').waitFor();
    await page.locator('#chat-form input').fill('Unsent text');
    await page.locator('[data-presence-user=bob].offline').waitFor();
    const bobContext = await browser.newContext();
    const bob = await bobContext.newPage();
    bob.on('pageerror', error => errors.push(error.message));
    await bob.goto(`${url}/#/campaign/camp/overview`);
    await bob.locator('#auth-form [name=username]').fill('Bob');
    await bob.locator('#auth-form [name=password]').fill(password);
    await bob.locator('#auth-form button').click();
    await bob.locator('a[href="#/campaigns"]').first().waitFor();
    await bob.evaluate(() => { location.hash = '#/campaign/camp/overview'; });
    await page.locator('[data-presence-user=bob].here').waitFor();
    assert.equal(await page.locator('#chat-form input').inputValue(), 'Unsent text');
    await bobContext.close();
    await page.locator('[data-presence-user=bob].offline').waitFor();
    await other.goto(`${url}/#/campaign/camp/overview`);
    await other.locator('.battle-panel').waitFor();
    await page.locator('[data-action=battle-action][data-value=start]').click();
    await other.locator('[data-action=battle-action][data-value=end]').waitFor();
    assert.equal(await page.locator('#chat-form input').inputValue(), 'Unsent text');
    const damage = page.locator('.campaign-resource[data-operation=damage]');
    await damage.locator('[name=amount]').fill('5');
    const resourceResponse = page.waitForResponse(response => response.url().endsWith('/api/campaigns/camp/resources') && response.request().method() === 'POST');
    await damage.locator('button').click();
    assert.equal((await resourceResponse).status(), 200);
    assert.equal(JSON.parse(db.prepare("SELECT data FROM entities WHERE id='test-character'").get().data).resources.hp.current, 95);
    assert.equal(await page.locator('#chat-form input').inputValue(), 'Unsent text');
    await page.waitForFunction(() => window.eventOpenCount >= 1);
    const cookie = (await context.cookies()).find(item => item.name === 'random_session');
    app.live.disconnectSession(digest(cookie.value));
    await page.waitForFunction(() => window.eventOpenCount >= 2, null, { timeout: 12000 });
    await other.close();

    let release;
    const gate = new Promise(resolve => { release = resolve; });
    let requested;
    const requestSeen = new Promise(resolve => { requested = resolve; });
    await page.route('**/api/entities?type=character', async route => { requested(); await gate; await route.continue(); });
    await page.evaluate(() => { location.hash = '#/characters'; });
    await requestSeen;
    await page.evaluate(() => { location.hash = '#/dice'; });
    await page.locator('#dice-form').waitFor();
    const delayedResponse = page.waitForResponse(response => response.url().includes('/api/entities?type=character'));
    release();
    await delayedResponse;
    assert.equal(await page.locator('#dice-form').count(), 1);
    await page.locator('#dice-form [name=expression]').fill('1d6');
    await page.locator('#dice-form button').click();
    await page.locator('#dice-result .result-total').first().waitFor();
    await page.unroute('**/api/entities?type=character');
    await page.goto(`${url}/#/generators`);
    await page.locator('.gen-workspace').waitFor();
    await page.locator('[data-action=gen-generate]').click();
    await page.locator('.gen-sheet article').waitFor();
    await page.goto(`${url}/#/rulebook`);
    const frame = page.frameLocator('.rulebook-frame');
    await frame.locator('#rulebook').waitFor();
    await frame.locator('.search-trigger').click();
    await frame.locator('#rule-search').fill('armor');
    await frame.locator('#search-results li').first().waitFor();
    await page.locator('[name=siteLanguage]').selectOption('fr');
    await page.waitForFunction(() => document.documentElement.lang === 'fr');
    await page.frameLocator('.rulebook-frame').locator('html[lang=fr]').waitFor();
    assert.ok(await page.evaluate(async () => (await document.fonts.load('18px Garamond')).some(font => font.status === 'loaded')));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${url}/#/campaign/camp/overview`);
    await page.locator('.battle-panel').waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.deepEqual(errors, []);
    console.log('Browser smoke passed: edits and two-tab locks, live battle and reconnect, navigation races, generator, rulebook, French, and mobile.');
    await context.close();
  } finally {
    if (browser) await browser.close();
    app.live.shutdown();
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
    db.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });

